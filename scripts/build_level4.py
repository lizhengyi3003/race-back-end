def merge_into_md(full_rows: list[list[str]]):
    """把第 4 级指标行追加到《农业及相关产业动态指标搜集体系.md》行业分层表末尾。"""
    md = DOCS_DIR / "农业及相关产业动态指标搜集体系.md"
    lines = md.read_text(encoding="utf-8").splitlines()
    # 去掉末尾空行
    while lines and not lines[-1].strip():
        lines.pop()
    lines.append("")
    lines.append("<!-- ============ 以下为第4级「具体营业类型」指标（自动生成 2026-08-07，共 %d 条） ============ -->" % len(full_rows))
    for r in full_rows:
        lines.append("| " + " | ".join(r) + " |")
    lines.append("")
    md.write_text("\n".join(lines), encoding="utf-8")
    print(f"已合并 md: {md}（新增 {len(full_rows)} 行）")


def merge_into_xlsx(full_rows: list[list[str]]):
    """把第 4 级指标行追加到《农业及相关产业动态指标搜集体系.xlsx》动态指标搜集体系 工作表末尾。"""
    import openpyxl

    xlsx = DOCS_DIR / "农业及相关产业动态指标搜集体系.xlsx"
    wb = openpyxl.load_workbook(xlsx)
    ws = wb["动态指标搜集体系"]
    before = ws.max_row
    for r in full_rows:
        ws.append(r)
    wb.save(xlsx)
    print(f"已合并 xlsx: {xlsx}（新增 {len(full_rows)} 行，{before} -> {ws.max_row}）")



def strip_suffix(name: str) -> str:
    n = name
    for _ in range(3):
        changed = False
        for suf in _SUFFIXES:
            if n.endswith(suf) and len(n) > len(suf) + 1:
                n = n[: -len(suf)]
                changed = True
                break
        if not changed:
            break
    return n

